# Задача 3.2.2 Шаги за неделю
# Фитнес-браслет передаёт количество шагов за каждый день. Вводятся числа шагов по одному, ввод заканчивается нулём. Выведите общее число шагов в формате Всего шагов: 53200.

total = 0
steps = int(input())
while steps != 0:
    total = total + steps
    steps = int(input())
print("Всего шагов: ",total)



