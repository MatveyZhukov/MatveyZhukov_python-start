# Заказ отправляют, когда он оплачен, товар есть на складе и адрес указан. Вводятся три ответа
# «да» или «нет»: оплачен ли заказ, есть ли товар, указан ли адрес. Выведите, можно ли отправлять.
# Отдельной строкой выведите, нужно ли звонить покупателю: звонят, если заказ оплачен, а адреса
# нет.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     да
#     да
#     да
#   в терминале:
#     Заказ оплачен (да/нет): да
#     Товар есть (да/нет): да
#     Адрес указан (да/нет): да
#     Можно отправлять: True
#     Позвонить покупателю: False
# Пример 2
#   ввод:
#     да
#     да
#     нет
#   в терминале:
#     Заказ оплачен (да/нет): да
#     Товар есть (да/нет): да
#     Адрес указан (да/нет): нет
#     Можно отправлять: False
#     Позвонить покупателю: True
# Пример 3
#   ввод:
#     нет
#     да
#     нет
#   в терминале:
#     Заказ оплачен (да/нет): нет
#     Товар есть (да/нет): да
#     Адрес указан (да/нет): нет
#     Можно отправлять: False
#     Позвонить покупателю: False

